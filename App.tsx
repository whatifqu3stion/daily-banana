// This component now serves as the main application entry point,
// managing state and orchestrating the comic generation workflow.
import React from 'react';
import useComicGeneration from './hooks/useComicGeneration';
import ComicForm from './components/ComicForm';
import LoadingState from './components/LoadingState';
import StorySwiper from './components/StorySwiper';
import ReviewPlan from './components/ReviewPlan';
import ComicStrip from './components/ComicStrip';
import BananaIcon from './components/icons/BananaIcon';

const App: React.FC = () => {
  const {
    appStage,
    formData,
    comicPlans,
    reviewData,
    comicStripData,
    isLoading,
    loadingMessages,
    progress,
    error,
    isPanelLoading,
    handleFormSubmit,
    handleSelectStory,
    handleContinueGeneration,
    handleUpdatePanel,
    handleRegeneratePanelImage,
    handleRefinePanelImage,
    handleStartNew,
    onRegenerateConcept,
    onRegenerateIdeas,
    onUpdateReviewImage,
    onReturnFromSwiper,
    onReturnFromReview,
  } = useComicGeneration();

  const renderContent = () => {
    if (isLoading && appStage !== 'strip') {
      return <LoadingState messages={loadingMessages} progress={progress} />;
    }

    if (error) {
      return (
        <div className="text-center my-4 p-4 bg-red-100 rounded-md border border-red-300 w-full max-w-3xl mx-auto">
          <h4 className="font-bold text-red-800">An Error Occurred</h4>
          <p className="text-red-700 mt-1">{error}</p>
          <button
            onClick={handleStartNew}
            className="mt-4 px-4 py-2 bg-red-600 text-white font-bold rounded hover:bg-red-700"
          >
            Start Over
          </button>
        </div>
      );
    }

    switch (appStage) {
      case 'form':
        return <ComicForm onSubmit={handleFormSubmit} isLoading={isLoading} />;
      case 'story-swipe':
        return (
          <StorySwiper
            storyPlans={comicPlans}
            onSelectStory={handleSelectStory}
            onRegenerate={onRegenerateIdeas}
            onReturnToForm={onReturnFromSwiper}
          />
        );
      case 'review':
        if (!reviewData) return <div>Error: No review data available.</div>;
        return (
          <ReviewPlan
            reviewData={reviewData}
            formData={formData}
            onContinue={handleContinueGeneration}
            onReturnToForm={onReturnFromReview}
            onRegenerateConcept={onRegenerateConcept}
            onUpdateReviewImage={onUpdateReviewImage}
          />
        );
      case 'strip':
        if (!comicStripData) return <div>Error: No comic data available.</div>;
        return (
          <ComicStrip
            comicData={comicStripData}
            onUpdatePanel={handleUpdatePanel}
            onRegeneratePanelImage={handleRegeneratePanelImage}
            onRefinePanelImage={handleRefinePanelImage}
            onStartNew={handleStartNew}
            onRegenerateComic={onRegenerateConcept} // Regenerating comic uses same logic as new concept
            isPanelLoading={isPanelLoading}
            footerCredit="A comic generated by "
            footerLinkText="The Daily Banana"
            footerLinkHref="https://github.com/google/generative-ai-docs/tree/main/apps/comic-gen"
            footerDisclaimer="This comic was generated with AI and is for entertainment purposes only."
          />
        );
      default:
        // Fallback for an invalid stage
        handleStartNew();
        return <ComicForm onSubmit={handleFormSubmit} isLoading={isLoading} />;
    }
  };

  return (
    <div className="min-h-screen bg-[#F3EAD3] p-4 sm:p-8 font-sans">
      <header className="text-center mb-8">
        <h1 className="text-5xl md:text-6xl font-bangers tracking-wider text-black flex items-center justify-center gap-2">
          <BananaIcon className="w-12 h-12" />
          The Daily Banana
        </h1>
        <p className="text-xl font-special-elite text-gray-800 mt-2">
          Your Daily Dose of AI-Generated Hilarity
        </p>
      </header>
      <main>
        {renderContent()}
      </main>
      <footer className="text-center mt-12 font-special-elite text-sm text-gray-600">
          <p>Built with the Google Gemini API.</p>
          <p>
            This is not an official Google product. View the source on{' '}
            <a href="https://github.com/google/generative-ai-docs/tree/main/apps/comic-gen" className="underline" target="_blank" rel="noopener noreferrer">
                GitHub
            </a>.
          </p>
      </footer>
    </div>
  );
};

export default App;
