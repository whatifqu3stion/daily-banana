// This component now serves as the main application entry point,
// managing state and orchestrating the comic generation workflow.
import React from 'react';
import useComicGeneration from './hooks/useComicGeneration';
import ComicForm from './components/ComicForm';
import LoadingState from './components/LoadingState';
import StorySwiper from './components/StorySwiper';
import ReviewPlan from './components/ReviewPlan';
import ComicStrip from './components/ComicStrip';
import ErrorState from './components/ErrorState'; // Import the new error component

const App: React.FC = () => {
  const {
    appStage,
    formData,
    comicPlans,
    reviewData,
    comicStripData,
    isLoading,
    loadingMessages,
    progress,
    error,
    isPanelLoading,
    handleFormSubmit,
    handleSelectStory,
    handleContinueGeneration,
    handleUpdatePanel,
    handleRegeneratePanelImage,
    handleRefinePanelImage,
    handleStartNew,
    onRegenerateConcept,
    onRegenerateIdeas,
    onUpdateReviewImage,
    onReturnFromSwiper,
    onReturnFromReview,
  } = useComicGeneration();

  const today = new Date().toLocaleDateString('en-US', {
    weekday: 'long',
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  const renderContent = () => {
    if (isLoading && appStage !== 'strip') {
      return <LoadingState messages={loadingMessages} progress={progress} />;
    }

    if (error) {
      return (
        <ErrorState error={error} onStartOver={handleStartNew} />
      );
    }

    switch (appStage) {
      case 'form':
        return <ComicForm onSubmit={handleFormSubmit} isLoading={isLoading} />;
      case 'story-swipe':
        return (
          <StorySwiper
            storyPlans={comicPlans}
            onSelectStory={handleSelectStory}
            onRegenerate={onRegenerateIdeas}
            onReturnToForm={onReturnFromSwiper}
          />
        );
      case 'review':
        if (!reviewData) return <div>Error: No review data available.</div>;
        return (
          <ReviewPlan
            reviewData={reviewData}
            formData={formData}
            onContinue={handleContinueGeneration}
            onReturnToForm={onReturnFromReview}
            onRegenerateConcept={onRegenerateConcept}
            onUpdateReviewImage={onUpdateReviewImage}
          />
        );
      case 'strip':
        if (!comicStripData) return <div>Error: No comic data available.</div>;
        return (
          <ComicStrip
            comicData={comicStripData}
            onUpdatePanel={handleUpdatePanel}
            onRegeneratePanelImage={handleRegeneratePanelImage}
            onRefinePanelImage={handleRefinePanelImage}
            onStartNew={handleStartNew}
            onRegenerateComic={onRegenerateConcept} // Regenerating comic uses same logic as new concept
            isPanelLoading={isPanelLoading}
            footerCredit="Another fine edition from "
            footerLinkText="The Daily Banana"
            footerLinkHref="https://github.com/google/generative-ai-docs/tree/main/apps/comic-gen"
            footerDisclaimer="This comic was generated by AI. All characters and events are fictional. Any resemblance to reality is purely coincidental and frankly, hilarious."
          />
        );
      default:
        // Fallback for an invalid stage
        handleStartNew();
        return <ComicForm onSubmit={handleFormSubmit} isLoading={isLoading} />;
    }
  };

  return (
    <div className="min-h-screen p-4 sm:p-8 font-sans">
      <header className="text-center mb-16">
        <div className="w-full max-w-3xl mx-auto h-1 bg-black mb-2"></div>
        <div className="flex items-end justify-center gap-4 max-w-3xl mx-auto">
          <img src="/banana-boy-mascot.png" alt="Banana Boy mascot" className="h-36 md:h-44 w-auto flex-shrink-0" />
          <div className="text-center w-max">
            <p className="text-2xl font-special-elite text-gray-800 tracking-extrawidest whitespace-nowrap">
              {today}
            </p>
            <h1 className="masthead-title font-masthead font-black text-5xl md:text-6xl text-black mt-1">
              The Daily Bannana
            </h1>
            <p className="text-xl font-special-elite text-gray-800 mt-2 whitespace-nowrap">
              The news makes us want to cry, but we choose to laugh.
            </p>
          </div>
        </div>
        <div className="w-full max-w-3xl mx-auto h-1 bg-black mt-2"></div>
      </header>
      <main>
        {renderContent()}
      </main>
      <footer className="text-center mt-12 font-special-elite text-gray-800">
          <p className="text-lg">
            Built with Google Nano Banana, made with 💛 by <a href="https://x.com/SummitSatoshi" target="_blank" rel="noopener noreferrer" className="underline hover:text-black">SummitSatoshi</a>
          </p>
          <p className="text-xs mt-2 max-w-3xl mx-auto">
            All content is the sole view of the creator, not the tool owner, by using this service you agree to comply with Google’s T.O.S. and all other applicable laws.
          </p>
      </footer>
    </div>
  );
};

export default App;